#if defined(_WIN32)
#  define ES_SCRIPT_API_LIB "jce_script_api.dll"
#  define es_setenv(k, v) _putenv_s((k), (v))
#elif defined(__APPLE__)
#  define ES_SCRIPT_API_LIB "libjce_script_api.dylib"
#  define es_setenv(k, v) setenv((k), (v), 1)
#else
#  define ES_SCRIPT_API_LIB "libjce_script_api.so"
#  define es_setenv(k, v) setenv((k), (v), 1)
#endif

void es_script_langs_register(void)
{
    es_preload_runtime();
#if defined(ES_HAVE_SCRIPT_PYTHON) || defined(ES_HAVE_SCRIPT_JAVA)
    char base[1024];
    char api_lib[1024 + sizeof ES_SCRIPT_API_LIB];
    api_lib[0] = '\0';
    if (jce_fs_host_get_base_path(base, (uint32_t)sizeof base) && base[0])
        snprintf(api_lib, sizeof api_lib, "%s%s", base, ES_SCRIPT_API_LIB);
#endif

#if defined(ES_HAVE_SCRIPT_PYTHON)
    /* CPython writes __pycache__ next to whatever it imports, and the
     * `jce_script` package is imported FROM THE REPOSITORY here.  Stale .pyc
     * is invalidated on (mtime, size), so a same-size edit inside one mtime
     * second leaves the OLD bytecode running — a real failure this worktree
     * has already had.  Set before Py_InitializeFromConfig, which has not run
     * yet: the interpreter does not exist until the first create. */
    es_setenv("PYTHONDONTWRITEBYTECODE", "1");
    if (api_lib[0])
        es_setenv("JCE_SCRIPT_API", api_lib);

    /* The one path CPython cannot discover: the directory holding the
     * `jce_script` package.  Without it `import jce_script.vm` fails and
     * instantiate returns 0 — the script is silently absent, not degraded. */
    if (!jce_script_vm_python_add_path(ES_SCRIPT_PYTHON_PACKAGE_DIR))
        fprintf(stderr,
                "ES scripting: sys.path refused '%s' — every .py in this "
                "scene will fail to instantiate\n",
                ES_SCRIPT_PYTHON_PACKAGE_DIR);
    if (!jce_script_vm_python_register())
        fprintf(stderr, "ES scripting: python register REFUSED — .py will "
                        "resolve to no language\n");
#endif

#if defined(ES_HAVE_SCRIPT_JAVA)
    {
        JceScriptVmJavaConfig cfg;
        static char           lib_opt[1024];
        const char           *opts[1];

        /* -Djce.script.library must be ABSOLUTE.  com.jce.script.JceScript's
         * static initialiser otherwise falls back to System.loadLibrary()
         * against a java.library.path this process never arranged, and the
         * shim is built beside jce_script_api rather than beside the exe. */
        snprintf(lib_opt, sizeof lib_opt, "-Djce.script.library=%s",
                 ES_SCRIPT_JAVA_SCRIPT_LIB);
        opts[0] = lib_opt;

        memset(&cfg, 0, sizeof cfg);
        /* An ABSOLUTE jvm library, because jce_library_open() attaches to an
         * already-resident module of the same bare name on Windows — "jvm.dll"
         * would bind to whichever JVM something else loaded first, with
         * somebody else's options.  configure() refuses a bare name for
         * exactly that reason. */
        cfg.jvm_library  = ES_SCRIPT_JAVA_JVM_LIBRARY;
        cfg.class_path   = ES_SCRIPT_JAVA_CLASS_PATH;
        cfg.options      = opts;
        cfg.option_count = 1;

        if (!jce_script_vm_java_configure(&cfg, sizeof cfg))
            fprintf(stderr,
                    "ES scripting: java configure REFUSED (jvm=%s, "
                    "classpath=%s) — jce_script_vm_create(\"java\") will "
                    "fail\n",
                    ES_SCRIPT_JAVA_JVM_LIBRARY, ES_SCRIPT_JAVA_CLASS_PATH);
        if (!jce_script_vm_java_register())
            fprintf(stderr, "ES scripting: java register REFUSED — .java "
                            "will resolve to no language\n");
    }
#endif

#if defined(ES_HAVE_SCRIPT_CPP)
    /* Order: register the LANGUAGE first, then the module and the extension
     * claim.  jce_script_vm_register_extension() refuses a claim for a
     * language that is not registered yet — deliberately, so that "backend
     * not linked" never turns into "extension resolves to a VM that does not
     * exist". */
    if (!jce_script_vm_cpp_register())
        fprintf(stderr, "ES scripting: cpp register REFUSED\n");
    else
        (void)es_flower_sway_register();
#endif

#if defined(ES_HAVE_SCRIPT_C)
    /* "c" IS A SEPARATE CALL AND A SEPARATE LANGUAGE.  It is not registered
     * by jce_script_vm_cpp_register() and it does not register that one:
     * a host that wants both calls both.  What the two SHARE is the native
     * class registry — one registry, because a compiled class has no language
     * at run time (it is a table of C function pointers) — which is why the
     * module below is published through jce_script_vm_cpp_add_module() even
     * though it is C.  jce_script_vm_c.h states the whole arrangement.
     *
     * TWO MODULES, NOT ONE WITH TWO CLASSES: one module descriptor is one
     * translation unit, and a translation unit is C or C++. */
    if (!jce_script_vm_c_register())
        fprintf(stderr, "ES scripting: c register REFUSED — .jcec will "
                        "resolve to no language\n");
    else
        (void)es_prop_surface_register();
#endif

    /* One line saying what this executable can actually run.  It is the
     * cheapest possible answer to "is the backend in this build at all",
     * which is the question every other symptom in this area reduces to. */
    {
        int i;
        int n = jce_script_vm_count();
        fprintf(stderr, "ES scripting: %d language(s) registered:", n);
        for (i = 0; i < n; ++i)
            fprintf(stderr, " %s", jce_script_vm_language_at(i));
        fprintf(stderr, "\nES scripting: extension claims:");
        n = jce_script_vm_extension_count();
        for (i = 0; i < n; ++i)
            fprintf(stderr, " .%s=%s", jce_script_vm_extension_at(i),
                    jce_script_vm_extension_language_at(i));
        fprintf(stderr, "\n");
    }
}
