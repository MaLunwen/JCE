/* ══ SUPERSEDED FOR THE SHIPPING BUILD ══════════════════════════════
 *
 * Everything below this guard is the hand-written version of the four steps,
 * and it is kept only for the in-tree branch that still configures that way.
 * The four steps are now engine-side: jce_script_enable() in the SDK links
 * the backends, bakes the runtime inputs and generates the registration shim,
 * and this file just calls it.
 *
 * WHY THIS MATTERS AND NOT JUST TIDINESS.  The hand-written version was
 * written into the IN-TREE CMake branch and not the SDK-consumer one this
 * project ships from, so the shipped executable ran Lua and nothing else
 * while the editor ran four languages -- with no build error anywhere.  A
 * per-project copy of a four-step contract is a copy that can be complete in
 * one branch and absent in another. */
