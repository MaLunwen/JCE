/*
 * es_script_langs.c — turn on the language backends this project's scene
 * uses, before anything in the scene is instantiated.
 *
 * ══ THE ANSWER TO "WHAT MUST A PROJECT DO TO GET PYTHON / JAVA / C++" ══
 *
 * Nothing in the engine does this for you and nothing can.  The engine
 * registers exactly ONE language for itself — the built-in Lua VM, lazily, on
 * first use (jce_script_vm.h, JCE_SCRIPT_VM_DEFAULT_LANGUAGE).  Every other
 * backend registers itself, from a function the APPLICATION calls, and if the
 * application never calls it the backend is not merely off: the extension is
 * unclaimed, jce_script_vm_language_for_path() returns NULL, and every entity
 * carrying such a script is REFUSED — loudly, but at runtime, with the scene
 * otherwise working perfectly.
 *
 * So the whole contract is four bullets, and each one of them is a thing that
 * fails on its own:
 *
 *   1. BUILD the backend.  JCE_BUILD_SCRIPT_JAVA defaults OFF; Python's target
 *      exists only where CMake found an embeddable CPython; the cpp backend
 *      needs no toolchain but does need its module compiled into something.
 *      See CMakeLists.txt in this directory's parent.
 *   2. LINK it, and link jce_script_api beside it — the shared library the
 *      Python and Java bindings CALL.  A missing DLL is a loader failure
 *      before main() and prints nothing.
 *   3. CALL its register().  That is this file.
 *   4. TELL IT WHERE ITS RUNTIME LIVES.  CPython needs the `jce_script`
 *      package on sys.path; the JVM needs an absolute jvm.dll, a class path,
 *      and the absolute path of the JNI shim.  None of the four is
 *      discoverable by the backend itself.
 *
 * ORDER MATTERS AND IT IS NOT ARBITRARY.  This function must run before
 * app_init() loads the startup scene, because the scene's Script components
 * are instantiated inside jce_runtime_create() and a language registered
 * afterwards is a language the scene has already been refused by.  es_app_init
 * in main.c calls it as its first statement, before app_init().
 *
 * NOTHING HERE FAILS THE PROCESS.  Every refusal is reported by name on
 * stderr and the run continues, so the failure surfaces as "python: 0 starts"
 * in the probe report rather than as a window that never opened.  A refusal
 * that killed the process would tell you less.
 */

#include "es_script_langs.h"

#include <jce/api.h>
#include <stdlib.h>

static JceLibrary s_runtime_preload;

/* Deployment may supply a dependency of its external language runtime. */
static void es_preload_runtime(void)
{
    const char *path = getenv("ES_RUNTIME_PRELOAD");
    if (!s_runtime_preload && path && path[0]) {
        s_runtime_preload = jce_library_open(path);
        if (!s_runtime_preload)
            LOG_WARN("es_script", "external runtime dependency failed: %s", path);
    }
}

void es_script_langs_shutdown(void)
{
    jce_library_close(s_runtime_preload);
    s_runtime_preload = NULL;
}
