/* Installed public C99 surface only; no engine-private headers or GPU. */
#include <jce/api.h>
#include <stdio.h>
#define REQUIRE(x) do { if (!(x)) { printf("JCE_SMOKE: FAIL water spectrum line %d\n", __LINE__); goto failed; } } while (0)

bool jce_smoke_water_spectrum(void)
{
    JceWaterFft *physical = NULL;
    JceScene *scene = jce_scene_create();
    REQUIRE(scene);
    JceSceneSkyCelestialSettings celestial = jce_scene_sky_celestial_default();
    REQUIRE(celestial.struct_size == sizeof celestial);
    REQUIRE(celestial.version == JCE_SCENE_SKY_CELESTIAL_VERSION);
    REQUIRE(!jce_scene_get_sky_celestial_settings(scene));
    celestial.star_intensity = 0.75f;
    celestial.moon_intensity = 1.25f;
    celestial.solar_flare_intensity = 0.25f;
    celestial.moon_phase = 0.5f;
    REQUIRE(jce_scene_set_sky_celestial_settings(scene, &celestial));
    REQUIRE(jce_scene_get_sky_celestial_settings(scene));
    REQUIRE(jce_scene_get_sky_celestial_settings(scene)->moon_phase == 0.5f);
    REQUIRE(jce_scene_set_sky_celestial_settings(scene, NULL));
    REQUIRE(!jce_scene_get_sky_celestial_settings(scene));
    JceSceneCloudShapeSettings shape = jce_scene_cloud_shape_default();
    REQUIRE(shape.struct_size == sizeof shape);
    REQUIRE(shape.version == JCE_SCENE_CLOUD_SHAPE_VERSION);
    REQUIRE(!jce_scene_get_cloud_shape_settings(scene));
    shape.curl_metres = 96.0f;
    REQUIRE(jce_scene_set_cloud_shape_settings(scene, &shape));
    REQUIRE(jce_scene_get_cloud_shape_settings(scene));
    REQUIRE(jce_scene_get_cloud_shape_settings(scene)->curl_metres == 96.0f);
    REQUIRE(jce_scene_set_cloud_shape_settings(scene, NULL));
    REQUIRE(!jce_scene_get_cloud_shape_settings(scene));
    JceEntity entity = jce_scene_create_entity(scene, "Installed spectrum");
    JceWaterComponent water = {0};
    water.water_mode = JCE_WATER_MODE_FFT;
    water.fft_resolution = 32;
    water.fft_patch_size = 128;
    water.fft_wind_speed = 10;
    water.fft_wind_dir_x = 1;
    water.fft_fetch = 100000;
    water.fft_amplitude = 0.001f;
    jce_scene_set_water(scene, entity, &water);
    JceWaterSpectrumComponent spectrum = jce_scene_water_spectrum_default();
    REQUIRE(spectrum.struct_size == sizeof spectrum);
    REQUIRE(spectrum.version == JCE_WATER_SPECTRUM_COMPONENT_VERSION);
    REQUIRE(spectrum.shading_flags == JCE_WATER_SPECTRUM_FILTER_NORMALS);
    spectrum.model = JCE_WATER_FFT_SPECTRUM_TMA;
    spectrum.depth = 8;
    jce_scene_set_water_spectrum(scene, entity, &spectrum);
    REQUIRE(jce_scene_has_water_spectrum(scene, entity));
    REQUIRE(jce_scene_get_water_spectrum(scene, entity)->depth == 8);
    JceWaterFoamComponent foam = jce_scene_water_foam_default();
    REQUIRE(foam.struct_size == sizeof foam);
    REQUIRE(foam.version == JCE_WATER_FOAM_COMPONENT_VERSION);
    foam.decay_rate = 0.75f;
    jce_scene_set_water_foam(scene, entity, &foam);
    REQUIRE(jce_scene_has_water_foam(scene, entity));
    REQUIRE(jce_scene_get_water_foam(scene, entity)->decay_rate == 0.75f);
    JceWaterCrestComponent crest = jce_scene_water_crest_default();
    REQUIRE(crest.struct_size == sizeof crest);
    REQUIRE(crest.version == JCE_WATER_CREST_COMPONENT_VERSION);
    crest.start_height = 0.4f;
    jce_scene_set_water_crest(scene, entity, &crest);
    REQUIRE(jce_scene_has_water_crest(scene, entity));
    REQUIRE(jce_scene_get_water_crest(scene, entity)->start_height == 0.4f);
    jce_scene_remove_water_crest(scene, entity);
    REQUIRE(!jce_scene_has_water_crest(scene, entity));
    JceWaterCausticsComponent caustic = jce_scene_water_caustics_default();
    REQUIRE(caustic.struct_size == sizeof caustic);
    REQUIRE(caustic.version == JCE_WATER_CAUSTICS_COMPONENT_VERSION);
    caustic.offset_x = -0.5f;
    jce_scene_set_water_caustics(scene, entity, &caustic);
    REQUIRE(jce_scene_has_water_caustics(scene, entity));
    REQUIRE(jce_scene_get_water_caustics(scene, entity)->offset_x == -0.5f);
    jce_scene_remove_water_caustics(scene, entity);
    REQUIRE(!jce_scene_has_water_caustics(scene, entity));
    JceWaterNearshoreComponent shore = jce_scene_water_nearshore_default();
    REQUIRE(shore.struct_size == sizeof shore);
    REQUIRE(shore.version == JCE_WATER_NEARSHORE_COMPONENT_VERSION);
    REQUIRE(shore.terrain == 0);
    shore.extent = 24.0f;
    jce_scene_set_water_nearshore(scene, entity, &shore);
    REQUIRE(jce_scene_has_water_nearshore(scene, entity));
    REQUIRE(jce_scene_get_water_nearshore(scene, entity)->extent == 24.0f);
    float surface_y = 123.0f, coverage = -1.0f;
    REQUIRE(!jce_scene_water_nearshore_surface(scene, entity, 0.0f, 0.0f, 1.0f,
        &surface_y, &coverage));
    REQUIRE(surface_y == 123.0f && coverage == -1.0f);
    jce_scene_remove_water_nearshore(scene, entity);
    REQUIRE(!jce_scene_has_water_nearshore(scene, entity));
    JceWaterMotionComponent motion = jce_scene_water_motion_default();
    REQUIRE(motion.struct_size == sizeof motion);
    REQUIRE(motion.version == JCE_WATER_MOTION_COMPONENT_VERSION);
    REQUIRE(motion.cascade_fraction == 0.0f && motion.phase_rate == 1.0f);
    REQUIRE(motion.horizontal_scale == 1.0f && motion.max_horizontal_displacement == 0.0f);
    motion.cascade_fraction = 0.3f;
    motion.phase_rate = 1.25f;
    motion.horizontal_scale = 0.75f;
    motion.max_horizontal_displacement = 2.0f;
    jce_scene_set_water_motion(scene, entity, &motion);
    REQUIRE(jce_scene_has_water_motion(scene, entity));
    REQUIRE(jce_scene_get_water_motion(scene, entity)->cascade_fraction == 0.3f);
    jce_scene_remove_water_motion(scene, entity);
    REQUIRE(!jce_scene_has_water_motion(scene, entity));
    JceWaterOpticsComponent optics = jce_scene_water_optics_default();
    REQUIRE(optics.struct_size == sizeof optics);
    REQUIRE(optics.version == JCE_WATER_OPTICS_COMPONENT_VERSION);
    REQUIRE(optics.ssr_strength == 0.0f && optics.refraction_strength == 0.0f);
    optics.ssr_strength = 0.75f;
    optics.refraction_strength = 0.5f;
    jce_scene_set_water_optics(scene, entity, &optics);
    REQUIRE(jce_scene_has_water_optics(scene, entity));
    REQUIRE(jce_scene_get_water_optics(scene, entity)->refraction_strength == 0.5f);
    jce_scene_remove_water_optics(scene, entity);
    REQUIRE(!jce_scene_has_water_optics(scene, entity));
    JceWaterCausticDetailComponent detail = jce_scene_water_caustic_detail_default();
    REQUIRE(detail.struct_size == sizeof detail);
    REQUIRE(detail.version == JCE_WATER_CAUSTIC_DETAIL_COMPONENT_VERSION);
    REQUIRE(detail.secondary_weight == 0.0f && detail.tile_size_m == 0.0f);
    REQUIRE(detail.transition_start_m == 0.5f && detail.transition_end_m == 4.0f);
    REQUIRE(detail.fine_period_ratio == 0.0f && detail.fine_weight == 0.0f);
    REQUIRE(detail.fine_fade_depth_m == 1.25f);
    detail.secondary_weight = 0.5f;
    detail.tile_size_m = 6.0f;
    detail.fine_period_ratio = 0.25f;
    detail.fine_weight = 0.75f;
    detail.fine_fade_depth_m = 2.0f;
    jce_scene_set_water_caustic_detail(scene, entity, &detail);
    REQUIRE(jce_scene_has_water_caustic_detail(scene, entity));
    REQUIRE(jce_scene_get_water_caustic_detail(scene, entity)->tile_size_m == 6.0f);
    REQUIRE(jce_scene_get_water_caustic_detail(scene, entity)->fine_period_ratio == 0.25f);
    REQUIRE(jce_scene_get_water_caustic_detail(scene, entity)->fine_weight == 0.75f);
    REQUIRE(jce_scene_get_water_caustic_detail(scene, entity)->fine_fade_depth_m == 2.0f);
    jce_scene_remove_water_caustic_detail(scene, entity);
    REQUIRE(!jce_scene_has_water_caustic_detail(scene, entity));
    JceWaterNormalDetailComponent normal_detail = jce_scene_water_normal_detail_default();
    REQUIRE(normal_detail.struct_size == sizeof normal_detail);
    REQUIRE(normal_detail.version == JCE_WATER_NORMAL_DETAIL_COMPONENT_VERSION);
    REQUIRE(normal_detail.frequency_low == 6.0f && normal_detail.frequency_high == 16.0f);
    REQUIRE(normal_detail.strength == 0.14f);
    REQUIRE(!jce_scene_has_water_normal_detail(scene, entity));
    normal_detail.frequency_low = 32.0f;
    normal_detail.frequency_high = 4.0f;
    normal_detail.strength = 0.25f;
    jce_scene_set_water_normal_detail(scene, entity, &normal_detail);
    REQUIRE(jce_scene_has_water_normal_detail(scene, entity));
    REQUIRE(jce_scene_get_water_normal_detail(scene, entity)->frequency_low == 32.0f);
    REQUIRE(jce_scene_get_water_normal_detail(scene, entity)->frequency_high == 4.0f);
    REQUIRE(jce_scene_get_water_normal_detail(scene, entity)->strength == 0.25f);
    jce_scene_remove_water_normal_detail(scene, entity);
    REQUIRE(!jce_scene_has_water_normal_detail(scene, entity));
    JceWaterField *field = jce_scene_acquire_water_field(scene, entity);
    REQUIRE(field && jce_water_field_fft(field));
    REQUIRE(jce_scene_acquire_water_field(scene, entity) == field);
    jce_scene_remove_water_foam(scene, entity);
    REQUIRE(!jce_scene_has_water_foam(scene, entity));
    REQUIRE(jce_scene_acquire_water_field(scene, entity) == field);
    jce_scene_remove_water_spectrum(scene, entity);
    REQUIRE(!jce_scene_has_water_spectrum(scene, entity));
    REQUIRE(jce_scene_acquire_water_field(scene, entity) == field);
    JceWaterFftSpectrumDesc config = {0};
    config.struct_size = sizeof(config);
    config.version = JCE_WATER_FFT_SPECTRUM_VERSION;
    config.model = JCE_WATER_FFT_SPECTRUM_PM;
    config.wind_speed = 10;
    config.fetch = 100000;
    config.depth = 50;
    config.seed = 17;
    physical = jce_water_fft_create(32, 128, 10, 1, 0, 0.001f, 17);
    REQUIRE(physical);
    REQUIRE(jce_water_fft_configure_spectrum(physical, &config));
    jce_water_fft_evolve(physical, 2);
    const float *height = jce_water_fft_height_data(physical);
    REQUIRE(height);
    double sum = 0, squared = 0;
    for (int i = 0; i < 32*32; ++i) {
        sum += height[i];
        squared += (double)height[i] * height[i];
    }
    const double mean = sum / 1024.0;
    const double variance = squared / 1024.0 - mean*mean;
    /* Broad physical bound for this finite PM sea; the old normalized
     * coefficients had variance near 2e-5 and cannot satisfy this check. */
    REQUIRE(variance > 0.04 && variance < 4.0);
    jce_water_fft_destroy(physical);
    jce_scene_destroy(scene);
    puts("JCE_SMOKE_WATER: installed spectrum, physical energy and shared field OK");
    return true;
failed:
    jce_water_fft_destroy(physical);
    if (scene) jce_scene_destroy(scene);
    return false;
}
