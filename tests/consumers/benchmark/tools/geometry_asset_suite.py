def write(path, value):
    path.write_text(json.dumps(value, indent=2)+"\n", encoding="utf-8", newline="\n")


def sphere_arrays(rings, slices):
    if type(rings) is not int or type(slices) is not int or not 2 <= rings <= 256 or not 3 <= slices <= 512:
        raise ValueError("bounded sphere resolutions required")
    positions = [(0., 1., 0.)]
    uv = [(0.5, 0.)]
    for ring in range(1, rings):
        theta = math.pi * ring / rings
        for sector in range(slices+1):
            phi = 2*math.pi*sector/slices
            positions.append((math.sin(theta)*math.cos(phi), math.cos(theta), math.sin(theta)*math.sin(phi)))
            uv.append((sector/slices, ring/rings))
    bottom = len(positions)
    positions.append((0., -1., 0.)); uv.append((0.5, 1.))
    indices = []
    for sector in range(slices):
        indices.extend((0, 1+sector+1, 1+sector))
    for ring in range(rings-2):
        for sector in range(slices):
            a = 1+ring*(slices+1)+sector; b = a+slices+1
            indices.extend((a, a+1, b, a+1, b+1, b))
    base = 1+(rings-2)*(slices+1)
    for sector in range(slices):
        indices.extend((bottom, base+sector, base+sector+1))
    # Right-handed outward winding is independent of UV seam duplication.
    for offset in range(0, len(indices), 3):
        a,b,c = (positions[i] for i in indices[offset:offset+3])
        ab = [b[i]-a[i] for i in range(3)]; ac = [c[i]-a[i] for i in range(3)]
        cross = (ab[1]*ac[2]-ab[2]*ac[1], ab[2]*ac[0]-ab[0]*ac[2], ab[0]*ac[1]-ab[1]*ac[0])
        if sum(cross[i]*(a[i]+b[i]+c[i]) for i in range(3)) <= 0:
            raise ValueError("non-outward or degenerate sphere triangle")
    return positions, uv, indices


def sphere_glb(rings, slices):
    positions, uv, indices = sphere_arrays(rings, slices)
    blocks = [struct.pack("<%uf"%(len(positions)*3), *(v for p in positions for v in p)),
              struct.pack("<%uf"%(len(positions)*3), *(v for p in positions for v in p)),
              struct.pack("<%uf"%(len(uv)*2), *(v for p in uv for v in p)),
              struct.pack("<%uI"%len(indices), *indices)]
    views = []; binary = b""
    for index, block in enumerate(blocks):
        views.append(dict(buffer=0, byteOffset=len(binary), byteLength=len(block), target=34963 if index==3 else 34962))
        binary += block
    doc = dict(asset=dict(version="2.0", generator="JCE original CC0 canonical UV sphere v1"),
        scene=0, scenes=[dict(nodes=[0])], nodes=[dict(mesh=0)], buffers=[dict(byteLength=len(binary))],
        bufferViews=views, accessors=[
            dict(bufferView=0, componentType=5126, count=len(positions), type="VEC3", min=[-1,-1,-1], max=[1,1,1]),
            dict(bufferView=1, componentType=5126, count=len(positions), type="VEC3"),
            dict(bufferView=2, componentType=5126, count=len(uv), type="VEC2"),
            dict(bufferView=3, componentType=5125, count=len(indices), type="SCALAR")],
        materials=[dict(pbrMetallicRoughness=dict(baseColorFactor=[.7,.2,.12,1], metallicFactor=0, roughnessFactor=.7))],
        meshes=[dict(primitives=[dict(attributes=dict(POSITION=0,NORMAL=1,TEXCOORD_0=2), indices=3, material=0, mode=4)])])
    encoded = json.dumps(doc, separators=(",", ":")).encode(); encoded += b" "*(-len(encoded)%4)
    content = (struct.pack("<III",0x46546c67,2,28+len(encoded)+len(binary)) +
               struct.pack("<II",len(encoded),0x4e4f534a)+encoded + struct.pack("<II",len(binary),0x004e4942)+binary)
    manifest = dict(generator_version=1,rings=rings,slices=slices,vertices=len(positions), indices=len(indices),
        source_triangles=len(indices)//3, degenerate_triangles=0, radius=1,
        position_sha256=hashlib.sha256(blocks[0]).hexdigest(), index_sha256=hashlib.sha256(blocks[3]).hexdigest(),
        glb_sha256=hashlib.sha256(content).hexdigest(), license="CC0-1.0", origin="Original mathematical fixture generated by JCE; no third-party model",
        topology_scope="Input accessor counts; NOT actual submitted vertices or triangles")
    return content, manifest


def fixture(asset, count, present=True):
    side = math.ceil(math.sqrt(count)); extent = side*3.5
    pose = transform(0, extent, 0); pose["rotX"]=-90
    entities = [dict(id=1,name="Camera",components=[pose,dict(type="Camera",primary=True,orthographic=True,
        orthoSize=extent,fov=40,nearClip=.1,farClip=extent*3,clearMode=1)]),
        dict(id=2,name="Sun",components=[transform(),dict(type="DirectionalLight",dirX=-.5,dirY=-1,dirZ=-.5,intensity=2)])]
    if present:
        for index in range(count):
            entities.append(dict(id=index+3,name="Sphere%u"%index,components=[
                transform((index%side-(side-1)/2)*3,0,(index//side-(side-1)/2)*3),
                dict(type="MeshRenderer",meshPath=asset,visible=True)]))
    return dict(entities=entities)


def validate_inventory(log, census, count, *, readiness):
    validate_still_controls(log)
    if "] ERROR -" in log: raise ValueError("renderer logged an error")
    rows = MARKER.findall(log)
    if not count:
        if rows or READY.findall(log): raise ValueError("empty control imported a model")
        return []
    if [int(row[0]) for row in rows] != [20,50]: raise ValueError("missing/duplicate actual topology observations")
    for row in rows:
        if tuple(map(int,row[1:8])) != (count,0,census["vertices"],1,0,0,0) or float(row[8])!=0 or int(row[9])<=0:
            raise ValueError("actual loaded population/topology differs")
    if readiness and (len(READY.findall(log))!=1 or int(READY.findall(log)[0][1])!=0):
        raise ValueError("actual readiness outside fixture frame zero")
    return rows


def cell_coverage(empty, present, count):
    if empty[:3] != present[:3] or empty[2] < 3:
        raise ValueError("capture size/channel mismatch")
    width,height,channels,a=empty; b=present[3]
    side=math.ceil(math.sqrt(count)); step=height/(side*3.5)
    values=[]
    for index in range(count):
        cx=width/2+(index%side-(side-1)/2)*3*step
        cy=height/2+(index//side-(side-1)/2)*3*step
        bounds=(int(cx-1.1*step),int(cy-1.1*step),int(cx+1.1*step)+1,int(cy+1.1*step)+1)
        x0,y0,x1,y1=bounds
        if not 0<=x0<x1<=width or not 0<=y0<y1<=height:raise ValueError("projected sphere cell outside viewport")
        values.append(sum(max(abs(a[(y*width+x)*channels+c]-b[(y*width+x)*channels+c]) for c in range(3))>5
                          for y in range(y0,y1) for x in range(x0,x1)))
    if len(values)!=count or min(values)<=0:raise ValueError("one or more authored sphere cells has no actual pixels")
    return values


def validate_exit(process):
    state = process.get("process", {})
    if state.get("returncode")!=0 or state.get("timed_out") is not False:
        raise ValueError("process failed or timed out")


def raw_hashes(directory):
    return {str(p.relative_to(directory)):sha256_file(p) for p in directory.rglob("*") if p.is_file()}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--exe",type=Path);parser.add_argument("--packer",type=Path)
    parser.add_argument("--out",type=Path,required=True)
    parser.add_argument("--backend",choices=("d3d11","d3d12","vulkan","gl"),default="d3d11")
    parser.add_argument("--dry-run",action="store_true")
    parser.add_argument("--timing",action="store_true")
    parser.add_argument("--repeats",type=int,choices=(3,7),default=7)
    args=parser.parse_args()
    if not args.dry_run and (not args.exe or not args.packer or not args.exe.is_file() or not args.packer.is_file()):
        parser.error("actual runs require existing --exe and --packer")
    args.out=args.out.resolve();args.out.mkdir(parents=True,exist_ok=False)
    result=dict(status="PLANNED",scope=__doc__,backend=args.backend,cases={},warmup=WARMUP,measured_frames=MEASURED,
        repeats=args.repeats,source=source_identity(),generator_sha256=sha256_file(Path(__file__)),
        actual_submitted_triangles=None,actual_submitted_vertices=None,
        limitations=["Public Player KPI does not expose per-model submitted triangle/vertex counts.",
            "No matched Unity/Unreal/Godot speed ratio; public benchmark assets are not proven identical.",
            "Whole-frame CPU/GPU observations, not isolated geometry GPU timestamps."])
    if args.exe: result["executable_sha256"]=sha256_file(args.exe)
    if args.packer: result["packer_sha256"]=sha256_file(args.packer)
    try:
        for name,count,rings,slices in CASES:
            directory=args.out/name;directory.mkdir();assets=directory/"assets";assets.mkdir()
            content,manifest=sphere_glb(rings,slices);asset=assets/"sphere.glb";asset.write_bytes(content)
            write(directory/"asset-manifest.json",manifest)
            (assets/"LICENSE.txt").write_text("Original generated sphere geometry dedicated to the public domain under CC0-1.0.\nhttps://creativecommons.org/publicdomain/zero/1.0/\n",encoding="ascii",newline="\n")
            census=glb_census(content);write(directory/"scene.json",fixture(asset.name,count))
            case=dict(count=count,manifest=manifest,census=census,captures={},timings=[],pixels=None)
            result["cases"][name]=case
            if args.dry_run:continue
            pak=pack_fixture(args.packer,asset,directory);pak_hash=sha256_file(pak);images={}
            for label,present,frame in (("empty",False,50),("base20",True,20),("base50",True,50),("repeat50",True,50)):
                target=directory/label;target.mkdir();scene=target/"scene.json";write(scene,fixture(asset.name,count,present))
                env=dict(JCE_SCENE=str(scene),JCE_BACKEND=args.backend,JCE_BENCH_ASSET_PAK=str(pak),
                    JCE_BENCH_ASSET_STILL="1",JCE_BENCH_TEXT_CAPTURE="1",JCE_BENCH_SHOT_FRAME=str(frame),JCE_GPU_SCENE="0",JCE_HIZ_OCCLUSION="0")
                if present:env.update(JCE_BENCH_ASSET_PATH=asset.name,JCE_BENCH_WAIT_ASSET="1",JCE_MAX_FRAMES="100000",JCE_MAX_SECONDS="75")
                fixture_hash=sha256_file(scene)
                process=run_visual_witness(env,target,exe=args.exe.resolve(),timeout=180,host="player")
                validate_exit(process);log=(target/"visual.log").read_text(encoding="utf-8")
                if sha256_file(scene)!=fixture_hash:raise ValueError("capture scene changed")
                assert_backend(log,args.backend);rows=validate_inventory(log,census,count if present else 0,readiness=True)
                resources=player_counters((target/"engine_counters.jsonl").read_text())
                if any(r["engine"]["entity_count"] != (count+2 if present else 2) for r in resources):raise ValueError("actual entity population differs")
                images[label]=read_png(target/"frame.png")
                if present and resources[-1].get("gpu",{}).get("draws",0)<=0:raise ValueError("backend submitted no draws")
                case["captures"][label]=dict(environment=env,process=process,topology=rows,resources=resources,scene_sha256=fixture_hash,raw_sha256=raw_hashes(target))
                print(json.dumps(dict(case=name,capture=label,population=count if present else 0)),flush=True)
            deltas=dict(coverage=full_pixel_difference(images["empty"],images["base50"],5),
                frame20_50=full_pixel_difference(images["base20"],images["base50"],5),repeat=full_pixel_difference(images["base50"],images["repeat50"],5))
            case["pixels"]=deltas
            case["per_cell_changed_pixels"]=cell_coverage(images["empty"],images["base50"],count)
            if not pixels_pass(deltas):raise ValueError("geometry coverage/still/repeat controls failed")
            if args.timing:
                for repeat in range(args.repeats):
                    target=directory/("timing-%u"%repeat);target.mkdir()
                    env=dict(case["captures"]["base50"]["environment"])
                    # Import must be observed by frame20 before measured120, no readiness clock hold/180-frame shutdown.
                    env.pop("JCE_BENCH_WAIT_ASSET");env.pop("JCE_BENCH_SHOT_FRAME")
                    env.pop("JCE_MAX_FRAMES");env.pop("JCE_MAX_SECONDS")
                    env.update(host_render_environment("player",target))
                    process=run(env,target/"engine.log",frames=WARMUP+MEASURED+1,timeout=900,exe=args.exe.resolve(),samples_path=target/"frames.csv")
                    validate_exit(process);log=(target/"engine.log").read_text();assert_backend(log,args.backend)
                    validate_inventory(log,census,count,readiness=False)
                    if sha256_file(Path(env["JCE_SCENE"]))!=case["captures"]["base50"]["scene_sha256"]:raise ValueError("timing fixture changed")
                    full=read_frames(target/"frames.csv",warmup=0,sample_count=None)
                    if len(full["frame_ms"])!=WARMUP+MEASURED+1:raise ValueError("actual measured frame interval count differs")
                    measured=read_frames(target/"frames.csv",warmup=WARMUP,sample_count=MEASURED)
                    resources=player_counters((target/"engine_counters.jsonl").read_text())
                    if any(r["engine"]["entity_count"]!=count+2 for r in resources):raise ValueError("timing actual population differs")
                    case["timings"].append(dict(environment=env,process=process,frame=frame_summary(measured),resources=resources,all_intervals=len(full["frame_ms"]),measured_interval_count=len(measured["frame_ms"]),raw_sha256=raw_hashes(target)))
            if sha256_file(asset)!=manifest["glb_sha256"] or sha256_file(pak)!=pak_hash:raise ValueError("canonical resource changed")
            write(args.out/"suite.json",result)
        if not args.dry_run and (sha256_file(args.exe)!=result["executable_sha256"] or sha256_file(args.packer)!=result["packer_sha256"]):raise ValueError("executable or packer changed")
        result["status"]="DRY_RUN_INPUT_VALIDATED" if args.dry_run else "GEOMETRY_LIVENESS_OBSERVED"
        if args.timing:result["timing_status"]="WHOLE_FRAME_OBSERVED" if not args.dry_run else "NOT_RUN"
        result["r03_metrics_status"]="INCOMPLETE_SUBMITTED_TOPOLOGY_UNAVAILABLE"
    except Exception as error:
        result.update(status="FAILED",error=str(error));raise
    finally:
        result["raw_sha256"]={str(p.relative_to(args.out)):sha256_file(p) for p in args.out.rglob("*") if p.is_file() and p!=args.out/"suite.json"}
        write(args.out/"suite.json",result)
    print(json.dumps(dict(suite=str(args.out/"suite.json"),status=result["status"])),flush=True)

if __name__=="__main__":main()
