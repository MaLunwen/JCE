"""Repair admitted IDE CMake metadata without deleting objects or package caches.

CMake versions sharing one binary directory retain separate system/compiler
descriptions. Retire this bounded set together when any version is unbound or
names a different compiler. Original and subsequently generated bytes remain
separate evidence; concurrent edits are never treated as rollback permission.
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import re

from tools.build import ide_jsonc as local

OWNER = "jce-ide-cmake-metadata"
TREE = re.compile(r"build/desktop/windows-(?:x86|x64|arm64)/obj/preset/(?:release|debug|dist|asan)")
VERSION = re.compile(r"[0-9]+\.[0-9]+(?:\.[0-9]+)?(?:-[A-Za-z0-9.]+)?")
COMPILER = re.compile(r"CMake[A-Za-z][A-Za-z0-9_]{0,31}Compiler\.cmake")
MAX_VERSIONS, MAX_FILES, MAX_TOTAL_BYTES = 16, 128, 8 * 1024 * 1024


def _digest(raw):
    return hashlib.sha256(raw).hexdigest() if raw is not None else None


def _path_key(value):
    return os.path.normcase(os.path.abspath(value.replace("\\", "/")))


def _tree(root, tree):
    relative = tree.relative_to(root).as_posix()
    if not TREE.fullmatch(relative):
        raise ValueError("CMake metadata repair requires a canonical Windows IDE tree")
    local._safe_path(root, relative)
    return relative


def _rows(raw):
    values = {}
    for line in raw.decode("utf-8-sig").splitlines():
        if line.startswith(("#", "//")) or "=" not in line or ":" not in line.split("=", 1)[0]:
            continue
        key, value = line.split("=", 1)
        key = key.split(":", 1)[0]
        if key in values:
            raise ValueError("duplicate CMake cache field: " + key)
        values[key] = value
    return values


def _inventory(root, relative):
    directory = local._safe_path(root, relative + "/CMakeFiles")
    if not directory.exists():
        return {}
    versions, files, total = 0, {}, 0
    for index, entry in enumerate(directory.iterdir()):
        if index >= 4096:
            raise ValueError("CMake metadata directory entry budget exceeded")
        if not VERSION.fullmatch(entry.name):
            continue
        version = local._safe_path(root, entry.relative_to(root).as_posix())
        if not version.is_dir():
            raise ValueError("CMake version metadata is not an ordinary directory")
        versions += 1
        if versions > MAX_VERSIONS:
            raise ValueError("CMake metadata version budget exceeded")
        for child_index, child in enumerate(version.iterdir()):
            if child_index >= 256:
                raise ValueError("CMake version entry budget exceeded")
            if child.name != "CMakeSystem.cmake" and not COMPILER.fullmatch(child.name):
                continue
            key = child.relative_to(root).as_posix()
            raw = local.read_file(root, key)
            if raw is None:
                raise ValueError("CMake metadata disappeared during inspection")
            files[key] = raw
            total += len(raw)
            if len(files) > MAX_FILES or total > MAX_TOTAL_BYTES:
                raise ValueError("CMake metadata file/byte budget exceeded")
    return dict(sorted(files.items()))


class Recovery:
    """Plan, back up and retire only stale generated descriptions."""

    def __init__(self, root: Path, tree: Path, toolchain: Path, compiler: str):
        self.root = root.resolve()
        self.tree = _tree(self.root, tree)
        self.cache = self.tree + "/CMakeCache.txt"
        self.cache_before = local.read_file(self.root, self.cache)
        self.reasons = []
        files = _inventory(self.root, self.tree)
        if files:
            if self.cache_before is None:
                raise ValueError("CMake metadata has no owning CMakeCache.txt")
            values = _rows(self.cache_before)
            if (not values.get("CMAKE_HOME_DIRECTORY")
                    or _path_key(values["CMAKE_HOME_DIRECTORY"]) != _path_key(str(self.root))
                    or values.get("CMAKE_GENERATOR") != "Ninja"
                    or (values.get("CMAKE_CACHEFILE_DIR") and
                        _path_key(values["CMAKE_CACHEFILE_DIR"]) != _path_key(str(tree)))):
                raise ValueError("CMake metadata cache belongs to another source, generator or directory")
            for version in sorted({Path(key).parent.as_posix() for key in files}):
                system = files.get(version + "/CMakeSystem.cmake")
                if system is None:
                    self.reasons.append(version + ": missing system description")
                else:
                    text = system.decode("utf-8-sig")
                    if not re.search(r"(?m)^set\(CMAKE_SYSTEM_LOADED\s+1\)\s*$", text):
                        raise ValueError("unrecognized generated CMake system description: " + version)
                    includes = re.findall(r'(?m)^include\("([^"\r\n]+)"\)\s*$', text)
                    if not any(_path_key(path) == _path_key(toolchain.as_posix()) for path in includes):
                        self.reasons.append(version + ": toolchain binding is absent or different")
                for language in ("C", "CXX"):
                    raw = files.get(version + "/CMake" + language + "Compiler.cmake")
                    if raw is None:
                        self.reasons.append(version + ": missing " + language + " compiler description")
                        continue
                    matches = re.findall(r'(?m)^set\(CMAKE_' + language +
                        r'_COMPILER\s+"([^"\r\n]+)"\)\s*$', raw.decode("utf-8-sig"))
                    if len(matches) != 1:
                        raise ValueError("unrecognized generated CMake compiler description: " + version)
                    if matches[0] != compiler:
                        self.reasons.append(version + ": " + language + " compiler identity differs")
        self.transaction = local.Transaction(self.root,
            {key: (raw, None) for key, raw in files.items()} if self.reasons else {})
        self.transaction.receipt.update(owner=OWNER, tree=self.tree, reasons=self.reasons)
        self.changes = self.transaction.changes
        self.backup = self.transaction.backup
        self.committed = False

    def apply(self):
        if not self.changes:
            return
        if local.read_file(self.root, self.cache) != self.cache_before:
            raise ValueError("CMake cache changed before metadata repair")
        self.transaction.apply()
        try:
            if local.read_file(self.root, self.cache) != self.cache_before:
                raise ValueError("CMake cache changed during metadata repair")
            saved = self.backup / "before" / self.cache
            local._atomic(saved, self.cache_before)
            self.transaction.receipt["cache_snapshot"] = {
                "path": self.cache, "before_sha256": _digest(self.cache_before), "after_sha256": None}
            self.transaction._receipt()
        except BaseException:
            self.transaction.rollback()
            raise

    def commit(self, *, configured=True):
        if not self.changes:
            return
        for row in self.transaction.receipt["files"]:
            row["after_sha256"] = _digest(local.read_file(self.root, row["path"]))
        self.transaction.receipt["cache_snapshot"]["after_sha256"] = _digest(
            local.read_file(self.root, self.cache))
        self.transaction.commit("REGENERATED_NOT_BUILT" if configured else "RETIRED_NOT_CONFIGURED")
        self.committed = True

    def rollback(self):
        if not self.changes or not self.backup.exists():
            return
        if self.committed:
            restore(self.root, self.backup)
            return
        # No launched tool's partial output is assumed to be ours. Preserve it
        # together with the original before asking the guarded remover to undo.
        changed_cache = local.read_file(self.root, self.cache) != self.cache_before
        for key in (*self.changes, self.cache):
            raw = local.read_file(self.root, key)
            if raw is not None:
                local._atomic(self.backup / "failed-configure" / key, raw)
        try:
            self.transaction.rollback()
        finally:
            self.transaction.receipt["cache_changed_during_configure"] = changed_cache
            self.transaction._receipt()
        if changed_cache:
            raise ValueError("CMake changed its cache during a failed configure; both snapshots retained at "
                             + str(self.backup))


def _backup(root, backup):
    if not backup.is_absolute():
        backup = root / backup
    if backup.parent != root / "build/validation/ide":
        raise ValueError("CMake metadata rollback requires one local IDE backup")
    key = backup.relative_to(root).as_posix()
    raw = local.read_file(root, key + "/receipt.json")
    if raw is None:
        raise ValueError("local IDE rollback receipt is missing")
    return backup, json.loads(raw.decode("utf-8-sig"))


def restore_resources(root, backup):
    """Resolve only the lease subject; full receipt admission is repeated later."""
    root = root.resolve()
    _path, receipt = _backup(root, backup)
    if receipt.get("owner") != OWNER:
        return []
    relative = receipt.get("tree", "")
    if not isinstance(relative, str) or not TREE.fullmatch(relative):
        raise ValueError("invalid CMake metadata receipt tree")
    local._safe_path(root, relative)
    return [root / relative]


def restore(root, backup, *, dry_run=False):
    root = root.resolve()
    backup, receipt = _backup(root, backup)
    tree = receipt.get("tree", "")
    if (receipt.get("schema") != 1 or receipt.get("owner") != OWNER
            or receipt.get("root") != str(root) or receipt.get("status") not in {"REGENERATED_NOT_BUILT", "RETIRED_NOT_CONFIGURED"}
            or not isinstance(tree, str) or not TREE.fullmatch(tree)):
        raise ValueError("CMake metadata rollback needs a successful receipt for this source root")
    rows, cache = receipt.get("files"), receipt.get("cache_snapshot")
    if not isinstance(rows, list) or not 1 <= len(rows) <= MAX_FILES or not isinstance(cache, dict):
        raise ValueError("CMake metadata rollback roster is invalid")
    desired, current, expected, total = {}, {}, {}, 0
    for row in [*rows, cache]:
        if not isinstance(row, dict) or set(row) != {"path", "before_sha256", "after_sha256"}:
            raise ValueError("CMake metadata rollback entry is invalid")
        key = row["path"]
        if not isinstance(key, str) or key in desired:
            raise ValueError("duplicate or invalid CMake metadata rollback path")
        suffix = Path(key).parts[len(Path(tree).parts):] if key.startswith(tree + "/") else ()
        allowed = (suffix == ("CMakeCache.txt",) if row is cache else
            len(suffix) == 3 and suffix[0] == "CMakeFiles" and VERSION.fullmatch(suffix[1])
            and (suffix[2] == "CMakeSystem.cmake" or COMPILER.fullmatch(suffix[2])))
        if not allowed:
            raise ValueError("unowned CMake metadata rollback path")
        saved_key = (backup / "before" / key).relative_to(root).as_posix()
        saved = local.read_file(root, saved_key)
        if saved is None or _digest(saved) != row["before_sha256"]:
            raise ValueError("CMake metadata backup identity differs: " + key)
        total += len(saved)
        if total > MAX_TOTAL_BYTES + local.MAX_BYTES:
            raise ValueError("CMake metadata rollback byte budget exceeded")
        after = row["after_sha256"]
        if after is not None and (not isinstance(after, str) or not re.fullmatch(r"[0-9a-f]{64}", after)):
            raise ValueError("CMake metadata published identity is invalid")
        desired[key], current[key], expected[key] = saved, local.read_file(root, key), after
    if all(current[key] == raw for key, raw in desired.items()):
        return {"status": "ALREADY_RESTORED", "files": len(rows) + 1, "backup": str(backup)}
    for key, raw in current.items():
        if _digest(raw) != expected[key]:
            raise ValueError("CMake metadata rollback preserved later changes: " + key)
    if dry_run:
        return {"status": "DRY_RUN", "files": len(rows) + 1, "backup": str(backup)}
    transaction = local.Transaction(root,
        {key: (current[key], raw) for key, raw in desired.items()}, validate_json=False)
    transaction.apply()
    try:
        transaction.commit("RESTORED_CMAKE_METADATA")
    except BaseException:
        transaction.rollback()
        raise
    return {"status": "RESTORED_CMAKE_METADATA", "files": len(rows) + 1,
            "backup": str(transaction.backup)}
